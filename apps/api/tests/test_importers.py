from app.importers import parse_file
import pytest


def test_ofx_positive_and_xml_entity_rejection():
    document=b'''OFXHEADER:100
DATA:OFXSGML
VERSION:102
SECURITY:NONE
ENCODING:USASCII
CHARSET:1252
COMPRESSION:NONE
OLDFILEUID:NONE
NEWFILEUID:NONE

<OFX><SIGNONMSGSRSV1><SONRS><STATUS><CODE>0</CODE><SEVERITY>INFO</SEVERITY></STATUS><DTSERVER>20261001120000</DTSERVER><LANGUAGE>POR</LANGUAGE></SONRS></SIGNONMSGSRSV1><BANKMSGSRSV1><STMTTRNRS><TRNUID>1</TRNUID><STATUS><CODE>0</CODE><SEVERITY>INFO</SEVERITY></STATUS><STMTRS><CURDEF>BRL</CURDEF><BANKACCTFROM><BANKID>001</BANKID><ACCTID>TEST-ONLY-ACCOUNT</ACCTID><ACCTTYPE>CHECKING</ACCTTYPE></BANKACCTFROM><BANKTRANLIST><DTSTART>20261001000000</DTSTART><DTEND>20261031000000</DTEND><STMTTRN><TRNTYPE>DEBIT</TRNTYPE><DTPOSTED>20261001120000</DTPOSTED><TRNAMT>-100.00</TRNAMT><FITID>isolated-fitid</FITID><NAME>Test fixture</NAME></STMTTRN></BANKTRANLIST><LEDGERBAL><BALAMT>0.00</BALAMT><DTASOF>20261031000000</DTASOF></LEDGERBAL></STMTRS></STMTTRNRS></BANKMSGSRSV1></OFX>'''
    rows=parse_file('fixture.ofx',document)
    assert len(rows)==1
    assert rows[0]['amount']=='-100.00'
    assert rows[0]['date']=='2026-10-01'
    assert 'TEST-ONLY-ACCOUNT' not in rows[0]['id']
    with pytest.raises(ValueError):
        parse_file('unsafe.ofx',b'<!DOCTYPE OFX [<!ENTITY x SYSTEM "file:///etc/passwd">]><OFX/>')
